def detect_parser_heading_conflict(text: str) -> bool:
    """Detect if official common.parse_answer was hijacked by a Markdown heading.
    
    In GSM8K candidates generated by small LLMs, text occasionally contains Markdown
    headings like '#### **Job 3**' or '#### Step 2' in the reasoning body, while the
    genuine final answer is placed in '\\boxed{...}'.
    Because common.parse_answer splits on the LAST '####', it extracts the heading number
    rather than the boxed answer, causing the official evaluator to score the candidate
    as incorrect (0 points).
    """
    text = str(text)
    parsed = common.parse_answer(text)
    if parsed is None:
        return False
    
    boxed = re.findall(r"\\boxed\{([^{}]+)\}", text)
    if not boxed:
        return False
    
    match = re.search(r"[-+]?\d[\d,]*(?:\.\d+)?(?:/\d+)?", boxed[-1])
    if not match:
        return False
    
    try:
        boxed_val = str(Fraction(match.group().replace(",", "")))
        return bool(boxed_val != parsed)
    except (ValueError, ZeroDivisionError):
        return False


def apply_validity_mask(
    logits: np.ndarray,
    bank: Sequence[Dict[str, Any]],
    penalty: float = 1e9,
) -> np.ndarray:
    """POST-P05: Mask out unparseable candidates (is_valid == 0).
    
    If at least one candidate for a question can be parsed by common.parse_answer,
    any candidate that cannot be parsed has its logit penalized by penalty (e.g. 1e9).
    This eliminates blind selection of unparseable candidates, recovering lost points
    on easy questions and preventing false selections on hard questions.
    """
    out = np.asarray(logits, dtype=np.float32).copy()
    n_questions = len(bank)
    if out.shape[0] != n_questions or out.shape[1] != 4:
        raise ValueError(f"Expected logits of shape ({n_questions}, 4), got {out.shape}")

    for i in range(n_questions):
        row = bank[i]
        cands = row["candidates"]
        valid_mask = [common.parse_answer(c["text"]) is not None for c in cands]
        if any(valid_mask):
            for c_idx, is_valid in enumerate(valid_mask):
                if not is_valid:
                    out[i, c_idx] = -float(penalty)
    return out


def apply_conflict_penalty(
    logits: np.ndarray,
    bank: Sequence[Dict[str, Any]],
    penalty: float = 1e9,
) -> np.ndarray:
    """POST-P05: Penalize candidates where Markdown headings hijack the official parser.
    
    If candidate text exhibits a parser heading conflict (detect_parser_heading_conflict),
    the official evaluator will score it 0 because it compares the hijacked heading
    number against gold. If there is at least one non-conflicting valid candidate in the
    question, apply penalty to the conflicting candidate.
    """
    out = np.asarray(logits, dtype=np.float32).copy()
    n_questions = len(bank)
    if out.shape[0] != n_questions or out.shape[1] != 4:
        raise ValueError(f"Expected logits of shape ({n_questions}, 4), got {out.shape}")

    for i in range(n_questions):
        row = bank[i]
        cands = row["candidates"]
        conflict_mask = [detect_parser_heading_conflict(c["text"]) for c in cands]
        valid_mask = [common.parse_answer(c["text"]) is not None for c in cands]
        
        # Only penalize if there is at least one candidate that is both valid and non-conflicting
        safe_candidates = [v and not conf for v, conf in zip(valid_mask, conflict_mask)]
        if any(safe_candidates):
            for c_idx, has_conf in enumerate(conflict_mask):
                if has_conf:
                    out[i, c_idx] = -float(penalty)
    return out


class SoftmaxClusterAggregator:
    """POST-P06: Intra-problem Softmax cluster aggregation.
    
    Given logits z [N, 4], computes candidate probabilities:
        P(c_i) = exp(z_i / T) / sum_j exp(z_j / T)
    Sums probabilities over identical parsed answers:
        Score(A_k) = sum_{c in A_k} P(c)
    Selects winning cluster A* = argmax Score(A_k).
    Ties between clusters are broken by highest individual candidate logit, then smaller index.
    Within winning cluster A*, selects the representative candidate with maximum logit.
    """

    def __init__(self, temperature: float = 1.0):
        if temperature <= 0:
            raise ValueError("Temperature must be positive")
        self.temperature = float(temperature)

    def aggregate(
        self,
        bank: Sequence[Dict[str, Any]],
        logits: np.ndarray,
    ) -> List[int]:
        """Aggregate logits into final candidate choices [N]."""
        z = np.asarray(logits, dtype=np.float64)
        n = len(bank)
        if z.shape[0] != n or z.shape[1] != 4:
            raise ValueError(f"Expected logits of shape ({n}, 4), got {z.shape}")

        # Numerically stable intra-problem softmax
        shifted = (z - np.max(z, axis=1, keepdims=True)) / self.temperature
        exp_z = np.exp(shifted)
        probs = exp_z / np.sum(exp_z, axis=1, keepdims=True)

        choices: List[int] = []
        for i in range(n):
            row = bank[i]
            cands = row["candidates"]
            cluster_probs: Dict[str, float] = defaultdict(float)
            cluster_cands: Dict[str, List[int]] = defaultdict(list)

            for c in range(4):
                ans = common.parse_answer(cands[c]["text"])
                if ans is not None:
                    cluster_probs[ans] += float(probs[i, c])
                    cluster_cands[ans].append(c)

            if not cluster_probs:
                # If all 4 candidates failed to parse, fallback to raw argmax
                choices.append(int(np.argmax(z[i])))
                continue

            # Rank clusters: highest probability sum, then highest member logit, then smaller index
            def cluster_rank(key: str):
                members = cluster_cands[key]
                return (
                    cluster_probs[key],
                    max(float(z[i, c]) for c in members),
                    -min(members),
                )

            best_cluster = max(cluster_probs.keys(), key=cluster_rank)
            best_cand = max(
                cluster_cands[best_cluster],
                key=lambda c: (float(z[i, c]), -c),
            )
            choices.append(int(best_cand))

        return choices
